import 'uzbek_alphabet.dart';

enum AppLang { uz, ru, en }

extension AppLangX on AppLang {
  String get code => switch (this) {
        AppLang.uz => 'UZ',
        AppLang.ru => 'RU',
        AppLang.en => 'EN',
      };

  String get apiCode => switch (this) {
        AppLang.uz => 'uz',
        AppLang.ru => 'ru',
        AppLang.en => 'en',
      };

  String pillCode(UzbekScript script) => switch (this) {
        AppLang.uz =>
          script == UzbekScript.reformed ? 'UZ · ĞÖŞÇ' : 'UZ',
        AppLang.ru => 'RU',
        AppLang.en => 'EN',
      };
}

class AppStrings {
  const AppStrings._();

  static String t(
    AppLang lang,
    String key, {
    UzbekScript script = UzbekScript.standard,
  }) {
    final map = switch (lang) {
      AppLang.uz => _uz,
      AppLang.ru => _ru,
      AppLang.en => _en,
    };
    final raw = map[key] ?? _uz[key] ?? key;
    if (lang == AppLang.uz) {
      return UzbekAlphabet.format(raw, script);
    }
    return raw;
  }

  /// Adapts dynamic Uzbek strings (contract titles, demo org names, clauses)
  /// to the active Uzbek script when [lang] is [AppLang.uz].
  static String adaptUz(String text, AppLang lang, UzbekScript script) {
    if (lang != AppLang.uz) return text;
    return UzbekAlphabet.format(text, script);
  }

